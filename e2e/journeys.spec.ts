test('narrow layout: navigation collapses and nothing overflows', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/results/ses-084');
  await expect(page.getByRole('link', { name: 'Compare' })).not.toBeInViewport();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('link', { name: 'Compare' }).click();
  await expect(page.getByRole('heading', { name: 'Compare performance' })).toBeVisible();
  for (const path of ['/results/ses-084', '/sessions', '/compare', '/publishing?source=ses-084']) {
    await page.goto('/#' + path);
    await page.waitForTimeout(200);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    expect(overflow, path).toBeLessThanOrEqual(0);
  }
});
