import { expect, test } from '@playwright/test';

const external: string[] = [];
test.beforeEach(async ({ page }) => {
  external.length = 0;
  // The demo must never contact a device, bot service or Notion.
  page.on('request', (req) => {
    const url = new URL(req.url());
    if (!['localhost', '127.0.0.1'].includes(url.hostname) && url.protocol !== 'data:' && url.protocol !== 'blob:') external.push(req.url());
  });
});
test.afterEach(() => {
  expect(external, 'no requests leave the demo').toEqual([]);
});

test('setup → record → stop & save → report', async ({ page }) => {
  await page.goto('/#/sessions');
  await expect(page.getByRole('heading', { name: 'Set up a performance session' })).toBeVisible();
  // Device profile limits: video is not offered over wireless on the test phone.
  await expect(page.getByRole('radio', { name: 'Video' })).toBeDisabled();
  await page.getByRole('radio', { name: 'USB' }).check();
  await expect(page.getByRole('radio', { name: 'Video' })).toBeEnabled();
  await page.getByLabel('Duration').selectOption('60');
  await page.getByLabel('Warm-up (excluded)').selectOption('10');
  await page.getByRole('button', { name: 'Start demo session' }).click();

  await expect(page).toHaveURL(/#\/live/);
  await expect(page.getByText('Simulated recording.')).toBeVisible();
  await page.getByLabel('Describe this moment').fill('Opened the shop');
  await page.getByRole('button', { name: 'Add marker' }).click();
  await page.waitForTimeout(1500);
  await page.getByRole('button', { name: 'Stop & save' }).click();

  await expect(page).toHaveURL(/#\/results\/ses-/);
  await expect(page.getByRole('heading', { name: 'Session report' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Opened the shop', exact: true })).toBeVisible();
  await expect(page.getByText('Simulated data generated by the demo simulator')).toBeVisible();
});

test('selecting a time links every chart and picks evidence within tolerance', async ({ page }) => {
  await page.goto('/#/results/ses-084');
  const fps = page.getByRole('slider', { name: /Frame rate/ });
  await fps.focus();
  // The first marker (12:33.4) is preselected; move to 12:34.4 with the keyboard.
  await page.keyboard.press('ArrowRight');
  await expect(fps).toHaveAttribute('aria-valuetext', /^12:34\.4/);
  await expect(page.getByRole('slider', { name: /Frame time/ })).toHaveAttribute('aria-valuetext', /^12:34\.4/);
  await expect(page.getByText(/Screenshot at 12:3\d\.\d/)).toBeVisible();
  await expect(page.getByText(/Offset [+−]\d\.\d s/)).toBeVisible();
  // Step through captures: the selected time follows the screenshot.
  await page.getByRole('button', { name: 'Next capture' }).click();
  await expect(page.getByText(/Screenshot at 12:3\d\.\d/)).toBeVisible();
});

test('a capture gap shows no evidence instead of a distant screenshot', async ({ page }) => {
  await page.goto('/#/results/ses-084-gaps');
  const chart = page.getByRole('slider', { name: /Frame rate/ });
  await chart.focus();
  await page.keyboard.press('Home');
  for (let i = 0; i < 52; i++) await page.keyboard.press('Shift+ArrowRight'); // 08:40, inside the 08:00–09:30 capture gap
  await expect(page.getByText('No nearby capture: captures are missing in this interval.')).toBeVisible();
  await expect(page.getByText('Permission denied').first()).toBeVisible();
});

