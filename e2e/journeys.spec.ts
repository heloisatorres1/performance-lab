test('a reload during recording becomes interrupted, never a silent resume', async ({ page }) => {
  await page.goto('/#/sessions');
  await page.getByRole('button', { name: 'Start demo session' }).click();
  await expect(page).toHaveURL(/#\/live/);
  await page.waitForTimeout(2500);
  await page.reload();
  await expect(page.getByText('Nothing is recording')).toBeVisible();
  await page.goto('/#/sessions');
  // The newest session is first in Recent sessions.
  await expect(page.getByRole('row').nth(1)).toContainText('Interrupted');
  await page.getByRole('row').nth(1).getByRole('link').click();
  await expect(page.getByText(/the page was closed/)).toBeVisible();
});

test('compare: mismatched conditions block the verdict until acknowledged', async ({ page }) => {
  await page.goto('/#/compare');
  await expect(page.getByText('All match')).toBeVisible();
  await expect(page.locator('.callout', { hasText: /Review needed · .*p95 frame time/ })).toBeVisible();
  await page.getByLabel('Candidate').selectOption({ label: 'Garden loop · USB · sensor denied (complete)' });
  await expect(page.getByText(/Verdict blocked/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Simulate publish' })).toBeDisabled();
  await page.getByLabel(/I understand these runs are not directly comparable/).check();
  await expect(page.locator('.callout', { hasText: /Limitations acknowledged/ })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Simulate publish' })).toBeEnabled();
});

test('failed publish keeps the report; retry after a timeout does not duplicate the page', async ({ page }) => {
  await page.goto('/#/publishing?source=ses-084');
  await page.getByLabel('Next page times out (but is created)').check();
  await page.getByRole('button', { name: 'Simulate publish' }).click();
  await expect(page.getByText('Uncertain · check before resending')).toBeVisible();
  await page.getByRole('button', { name: 'Check & retry' }).click();
  await expect(page.getByText('Published', { exact: true })).toBeVisible();
  await expect(page.getByText('1 page, 4 attachments')).toBeVisible();
  // The seeded failed publication (permission error) can be retried too.
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.getByText('Published', { exact: true })).toHaveCount(2);
});

