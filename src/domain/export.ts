export const EXPORT_SCHEMA = 'performance-lab.session/v1';

/** Neutralises spreadsheet formula injection and quotes when needed. */
export function csvCell(v: unknown): string {
  if (v === null || v === undefined) return '';
  let s = typeof v === 'number' ? (Number.isFinite(v) ? String(v) : '') : String(v);
  if (typeof v === 'string' && /^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export const csvRow = (cells: unknown[]) => cells.map(csvCell).join(',');

export function escapeHtml(s: string) {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

export function telemetryCsv(r: Report): string {
  const rows = [csvRow(['t_ms', 't_s', 'metric', 'value', 'unit', 'scope', 'source', 'aggregation'])];
  for (const [m, samples] of Object.entries(r.tel.series) as [MetricId, { t: number; v: number | null }[]][]) {
    const def = METRICS[m];
    for (const x of samples) rows.push(csvRow([x.t, (x.t / 1000).toFixed(3), m, x.v, def.unit, def.scope, def.source, def.aggregation]));
  }
  return rows.join('\n') + '\n';
}

export function framesCsv(r: Report): string {
  const rows = [csvRow(['present_t_ms', 'frame_interval_ms'])];
  for (let i = 0; i < r.tel.frameT.length; i++) rows.push(`${r.tel.frameT[i].toFixed(3)},${r.tel.frameDt[i].toFixed(3)}`);
  return rows.join('\n') + '\n';
}

export function eventsCsv(r: Report): string {
  const rows = [csvRow(['t_ms', 'kind', 'label'])];
  for (const e of r.tel.events) rows.push(csvRow([e.t, e.kind, e.label]));
  for (const a of r.session.annotations) rows.push(csvRow([a.t, 'annotation', a.text]));
  for (const g of r.tel.gaps) rows.push(csvRow([g.fromMs, `${g.stream}-gap`, `until ${g.toMs} ms`]));
  return rows.join('\n') + '\n';
}

const captureFile = (i: number) => `captures/${String(i).padStart(4, '0')}.svg`;

/** Video sessions bundle one still every 2 s; the video file itself is not part of the demo. */
export function bundledCaptures(r: Report) {
  if (r.session.config.capture !== 'video') return r.tel.captures;
  let last = -Infinity;
  return r.tel.captures.filter((c) => (c.t - last >= 2000 ? ((last = c.t), true) : false));
}

export function manifest(r: Report) {
  const s = r.session;
  const c = s.config;
  return {
    schema: EXPORT_SCHEMA,
    simulated: true,
    note: 'Demo data generated by a deterministic simulator. Not measured on a real device.',
    session: { id: s.id, name: s.name, state: s.state, endReason: s.endReason ?? null, recordedMs: s.recordedMs, createdAt: s.createdAt, startedAtWall: s.startedAtWall ?? null, seed: s.seed, continuationOf: s.continuationOf ?? null },
    conditions: {
      project: project(c.projectId)?.name,
      build: build(c.buildId)?.version,
      device: device(c.deviceId),
      scenario: scenario(c.scenarioId)?.name,
      connection: c.connection,
      playMode: c.playMode,
      botScriptId: c.botScriptId ?? null,
      capture: c.capture,
      requestedCaptureIntervalSec: c.capture === 'screenshots' ? c.captureIntervalSec : null,
      targetFps: c.targetFps,
      durationSec: c.durationSec,
      warmupSec: c.warmupSec,
      sampleHz: c.sampleHz,
      notes: c.notes,
      tags: c.tags,
    },
    collectorVersions: s.collectorVersions,
    metrics: Object.fromEntries(Object.entries(r.availability).map(([m, a]) => [m, { availability: a, ...METRICS[m as MetricId] }])),
    timeline: { clock: 'monotonic session time in ms; wall clock is metadata only', gaps: r.tel.gaps, events: r.tel.events, annotations: s.annotations },
    analysis: {
      frameWindow: r.frames?.window ?? null,
      definitions: DEFINITIONS,
      frames: r.frames,
      memory: r.memory,
      cpu: r.cpu,
      temperature: r.temperature,
      battery: r.battery,
      loadTime: r.load,
    },
    verdict: r.verdict,
    files: {
      report: 'report.html',
      telemetry: 'streams/telemetry.csv',
      frames: 'streams/frames.csv',
      events: 'streams/events.csv',
      captures: bundledCaptures(r).map((x) => ({ index: x.index, t: x.t, file: captureFile(x.index) })),
    },
  };
}

export const DEFINITIONS = {
  averageFps: 'Valid presented frames ÷ valid observed seconds in the analysis window. Gaps are excluded from both.',
  frameTime: 'Interval between consecutive eligible presented frames. Intervals spanning a gap are excluded.',
  percentiles: 'Nearest-rank on raw eligible frame intervals; no interpolation and no derivation from average FPS.',
  belowTarget: 'Share of valid 1 s windows whose frame count is below the configured threshold. Windows without data are excluded, not counted as zero.',
  slowFrames: 'Frames whose interval exceeds 2 × the target frame time.',
  memory: 'Proportional set size (PSS) of the game process, stored in MB. 1 GB = 1024 MB.',
  temperature: 'Battery temperature sensor. Not CPU or skin temperature.',
  battery: 'Level change in percentage points over the full session, including warm-up. pp/hour is an observed short-interval rate, not a battery-life prediction.',
  power: 'Watts = volts × amps from samples taken at the same timestamp. Whole-device battery power, not game-only energy.',
  alignment: 'Captures are matched to the selected time within ±1.5 s. Outside that, no capture is shown.',
};

function svgChart(points: { t: number; v: number | null }[], endMs: number, color: string, unit: string, height = 120): string {
  const W = 720;
  const vals = points.filter((p) => p.v !== null).map((p) => p.v as number);
  if (!vals.length) return '<p>No data.</p>';
  let lo = Math.min(...vals);
  let hi = Math.max(...vals);
  if (hi === lo) hi = lo + 1;
  const pad = (hi - lo) * 0.1;
  lo -= pad;
  hi += pad;
  const x = (t: number) => (t / endMs) * (W - 50) + 45;
  const y = (v: number) => height - 18 - ((v - lo) / (hi - lo)) * (height - 28);
  let d = '';
  let pen = false;
  for (const p of points) {
    if (p.v === null) {
      pen = false;
      continue;
    }
    d += `${pen ? 'L' : 'M'}${x(p.t).toFixed(1)} ${y(p.v).toFixed(1)}`;
    pen = true;
  }
  return `<svg viewBox="0 0 ${W} ${height}" role="img" aria-label="Chart in ${escapeHtml(unit)}"><text x="4" y="${y(hi - pad) + 4}" font-size="10" fill="#9fb0bf">${(hi - pad).toFixed(1)}</text><text x="4" y="${y(lo + pad) + 4}" font-size="10" fill="#9fb0bf">${(lo + pad).toFixed(1)}</text><path d="${d}" fill="none" stroke="${color}" stroke-width="1.5"/><text x="45" y="${height - 4}" font-size="10" fill="#9fb0bf">00:00</text><text x="${W - 5}" y="${height - 4}" font-size="10" fill="#9fb0bf" text-anchor="end">${fmtClock(endMs)}</text></svg>`;
}

