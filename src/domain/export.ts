export function exportBundle(r: Report): { name: string; bytes: Uint8Array; entries: ZipEntry[] } {
  const entries: ZipEntry[] = [
    { path: 'manifest.json', content: JSON.stringify(manifest(r), null, 2) },
    { path: 'report.html', content: reportHtml(r) },
    { path: 'streams/telemetry.csv', content: telemetryCsv(r) },
    { path: 'streams/frames.csv', content: framesCsv(r) },
    { path: 'streams/events.csv', content: eventsCsv(r) },
    ...bundledCaptures(r).map((c) => ({ path: captureFile(c.index), content: captureSvg(c, r.session.seed) })),
  ];
  const safe = r.session.name.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase() || r.session.id;
  return { name: `performance-lab-${safe}.zip`, bytes: zip(entries), entries };
}
